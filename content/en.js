          <p>In his role as a content creator, he spearheads the audiovisual and photographic direction of his own aesthetic projects. Within the literary field, he complements his creative sensibility through the publication of four printed books of his authorship, encompassing existentialist poetry with over three hundred compiled poems and personal short stories capturing everyday narratives, while also collaborating with the emblematic cultural magazine Sinfónica in Uruguay and Letras de Parnaso in Spain.</p>
